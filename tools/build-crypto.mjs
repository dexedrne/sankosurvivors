// Development inputs only; production deploys the checked CommonJS bundle with no package install.
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build, version } from 'esbuild';

const root = new URL('../', import.meta.url);
const read = async path => JSON.parse(await readFile(new URL(path, root), 'utf8'));
const pkg = await read('package.json'), lock = await read('package-lock.json');
const mode = process.argv[2];
assert.ok(process.argv.length === 3 && ['--check', '--write'].includes(mode), 'usage: node tools/build-crypto.mjs --check|--write');
for (const name of ['@noble/curves', '@noble/hashes']) {
  const expected = pkg.devDependencies[name];
  assert.equal(lock.packages['node_modules/' + name].version, expected, name + ' lock mismatch');
  assert.equal((await read('node_modules/' + name + '/package.json')).version, expected, name + ' installed version mismatch');
}
assert.equal(version, lock.packages['node_modules/esbuild'].version, 'esbuild lock mismatch');
const result = await build({
  entryPoints: [fileURLToPath(new URL('tools/vercel-api/noble-entry.mjs', root))],
  bundle: true, platform: 'node', format: 'cjs', target: 'node22', minify: true,
  legalComments: 'inline', write: false,
  banner: { js: `/*! secp256k1 + keccak-256 from @noble/curves ${pkg.devDependencies['@noble/curves']} and @noble/hashes ${pkg.devDependencies['@noble/hashes']} (MIT, (c) Paul Miller, paulmillr.com).
    Generated by tools/build-crypto.mjs; full license in noble-LICENSE.txt. */` },
});
const path = new URL('tools/vercel-api/noble-crypto.cjs', root), expected = result.outputFiles[0].text;
const licensePath = new URL('tools/vercel-api/noble-LICENSE.txt', root);
const license = await readFile(new URL('node_modules/@noble/curves/LICENSE', root), 'utf8') + await readFile(new URL('node_modules/@noble/hashes/LICENSE', root), 'utf8');
if (mode === '--write') { await writeFile(path, expected); await writeFile(licensePath, license); }
else {
  assert.equal(await readFile(path, 'utf8') === expected, true, 'cryptography bundle differs; review sources and run node tools/build-crypto.mjs --write');
  assert.equal(await readFile(licensePath, 'utf8') === license, true, 'cryptography license differs');
}
console.log('cryptography bundle ' + (mode === '--check' ? 'verified' : 'written'));
